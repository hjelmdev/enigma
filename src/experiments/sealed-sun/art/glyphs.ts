export type GlyphId = keyof typeof raw;
export const GLYPH_SIZE = 13;

export interface Glyph {
  id: GlyphId;
  size: number;
  /** Row-major 0/1 mask. */
  mask: Uint8Array;
}

function compile(id: GlyphId): Glyph {
  const rows = raw[id];
  const mask = new Uint8Array(GLYPH_SIZE * GLYPH_SIZE);
  rows.forEach((row, y) => {
    for (let x = 0; x < GLYPH_SIZE; x++)
      mask[y * GLYPH_SIZE + x] = row[x] === '#' ? 1 : 0;
  });
  return { id, size: GLYPH_SIZE, mask };
}

const compiled = new Map<GlyphId, Glyph>();

export function glyph(id: GlyphId): Glyph {
  let g = compiled.get(id);
  if (!g) {
    g = compile(id);
    compiled.set(id, g);
  }
  return g;
}

export function glyphOn(g: Glyph, x: number, y: number) {
  return (
    x >= 0 && y >= 0 && x < g.size && y < g.size && g.mask[y * g.size + x] === 1
  );
}

export const ALL_GLYPHS = Object.keys(raw) as GlyphId[];

/** Validation helper for tests: rows must all be exactly GLYPH_SIZE wide. */
export function glyphRowWidths(id: GlyphId) {
  return raw[id].map((row) => row.length);
}
